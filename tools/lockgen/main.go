// Command lockgen generates components/components.lock from
// components/components.yaml.
//
// For every component it resolves the chart to a digest, renders the chart to
// find the images it needs, resolves each image to a digest, and verifies the
// image the way components.yaml says. Nothing is written unless every image
// verifies.
//
// It needs helm, crane and cosign on PATH and network access to the upstream
// registries. Run it in the tools container:
//
//	docker compose --profile tools run --rm tools go run ./tools/lockgen
//
// With -check it regenerates the lock in memory and fails if it differs from
// the file. A difference means components.yaml changed without regenerating,
// or an upstream tag now points at different content.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"go.yaml.in/yaml/v3"

	"github.com/c-j-p-nordquist/argocd-kargo-deploy/components"
)

const header = `# Generated by tools/lockgen from components.yaml. Do not edit.
#
# Every chart and image is pinned by digest. Each image was verified as its
# "verification" entry describes when this file was generated. Charts are
# pinned by digest but not signature-checked. Each chart is rendered to the
# manifest file named here, whose hash is checked before it is used.
`

func main() {
	dir := flag.String("dir", "components", "directory holding components.yaml and components.lock")
	check := flag.Bool("check", false, "fail if the lock file is out of date instead of writing it")
	flag.Parse()

	if err := run(*dir, *check); err != nil {
		fmt.Fprintln(os.Stderr, "lockgen:", err)
		os.Exit(1)
	}
}

func run(dir string, check bool) error {
	data, err := os.ReadFile(filepath.Join(dir, "components.yaml"))
	if err != nil {
		return err
	}
	cfg, err := components.ParseConfig(data)
	if err != nil {
		return err
	}

	lock := components.Lock{SchemaVersion: components.SchemaVersion}
	for _, c := range cfg.Components {
		fmt.Fprintf(os.Stderr, "== %s %s\n", c.Name, c.Version)
		// The cooldown guards the moment a version is adopted. A check of an
		// existing lock must keep passing as time moves on, so it skips it.
		cooldown := cfg.CooldownDays
		if check {
			cooldown = 0
		}
		comp, err := resolve(dir, c, cooldown)
		if err != nil {
			return fmt.Errorf("%s: %w", c.Name, err)
		}
		lock.Components = append(lock.Components, comp)
	}

	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(lock); err != nil {
		return err
	}
	if _, err := components.ParseLock(buf.Bytes()); err != nil {
		return fmt.Errorf("generated lock is not valid: %w", err)
	}

	manifests["components.lock"] = buf.Bytes()
	if check {
		for path, want := range manifests {
			got, err := os.ReadFile(filepath.Join(dir, path))
			if err != nil {
				return err
			}
			if !bytes.Equal(got, want) {
				return fmt.Errorf("%s is out of date: components.yaml changed without regenerating, or an upstream tag now points at different content", path)
			}
		}
		fmt.Fprintln(os.Stderr, "the lock and rendered manifests are up to date and every image verified")
		return nil
	}

	// Replace the rendered directory so a removed component leaves nothing
	// behind.
	if err := os.RemoveAll(filepath.Join(dir, "rendered")); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(dir, "rendered"), 0o755); err != nil {
		return err
	}
	for path, data := range manifests {
		if err := os.WriteFile(filepath.Join(dir, path), data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func resolve(dir string, c components.ComponentConfig, cooldownDays int) (components.Component, error) {
	comp := components.Component{Name: c.Name, Purpose: c.Purpose, Optional: c.Optional, Namespace: c.Namespace}

	digest, err := output("crane", "digest", c.Chart+":"+c.Version)
	if err != nil {
		return comp, err
	}
	pinned := c.Chart + "@" + digest
	created, err := chartCreated(pinned)
	if err != nil {
		return comp, err
	}
	if age := time.Since(created); age < time.Duration(cooldownDays)*24*time.Hour {
		return comp, fmt.Errorf("chart %s was published %s, which is %d day(s) ago; the cooldown is %d days",
			c.Version, created.Format("2006-01-02"), int(age.Hours()/24), cooldownDays)
	}
	comp.Chart = components.Chart{
		Repository: c.Chart,
		Version:    c.Version,
		Digest:     digest,
		Created:    created.UTC().Format(time.RFC3339),
	}

	// Render the exact chart that was pinned, not whatever the tag points at
	// by the time helm pulls it.
	args := []string{"template", c.Release, "oci://" + pinned,
		"--namespace", c.Namespace,
		"--kube-version", components.KubeVersion,
		"--include-crds", "--skip-tests"}
	for _, set := range c.Set {
		args = append(args, "--set", set)
	}
	rendered, err := output("helm", args...)
	if err != nil {
		return comp, err
	}
	// A chart that generates certificates or random values while rendering
	// would give different manifests each time, and the secrets would end up
	// in this repository. Refuse it.
	again, err := output("helm", args...)
	if err != nil {
		return comp, err
	}
	if rendered != again {
		return comp, errors.New("the chart does not render the same way twice; it probably generates secrets or certificates at render time, which must be turned off with a set value")
	}
	refs, err := components.ImageRefs([]byte(rendered))
	if err != nil {
		return comp, err
	}
	if len(refs) == 0 {
		return comp, errors.New("the rendered chart contains no images")
	}

	for _, ref := range refs {
		img, err := resolveImage(dir, c, ref)
		if err != nil {
			return comp, fmt.Errorf("image %s: %w", ref, err)
		}
		fmt.Fprintf(os.Stderr, "   %-18s %s:%s\n", img.Verification.Method, img.Repository, img.Tag)
		comp.Images = append(comp.Images, img)
		rendered = pin(rendered, ref, img.PinnedRef())
	}

	manifest := []byte(rendered + "\n")
	sum := sha256.Sum256(manifest)
	comp.Manifest = components.Manifest{
		Path:   "rendered/" + c.Name + ".yaml",
		SHA256: hex.EncodeToString(sum[:]),
	}
	manifests[comp.Manifest.Path] = manifest
	return comp, nil
}

// chartCreated returns when the chart was published, from the annotation the
// registry stores on its manifest.
func chartCreated(pinned string) (time.Time, error) {
	raw, err := output("crane", "manifest", pinned)
	if err != nil {
		return time.Time{}, err
	}
	var manifest struct {
		Annotations map[string]string `json:"annotations"`
	}
	if err := json.Unmarshal([]byte(raw), &manifest); err != nil {
		return time.Time{}, fmt.Errorf("chart manifest: %w", err)
	}
	const key = "org.opencontainers.image.created"
	value := manifest.Annotations[key]
	if value == "" {
		return time.Time{}, fmt.Errorf("chart manifest has no %s annotation, so its age cannot be checked", key)
	}
	created, err := time.Parse(time.RFC3339, value)
	if err != nil {
		return time.Time{}, fmt.Errorf("chart manifest: %s: %w", key, err)
	}
	return created, nil
}

// manifests collects the rendered manifests by path, to write or compare once
// every component has resolved.
var manifests = map[string][]byte{}

// pin replaces every occurrence of an image reference with its digest-pinned
// form, without touching a longer reference that merely starts with it.
func pin(rendered, ref, pinned string) string {
	re := regexp.MustCompile(regexp.QuoteMeta(ref) + `($|[^A-Za-z0-9._@-])`)
	return re.ReplaceAllString(rendered, strings.ReplaceAll(pinned, "$", "$$")+"${1}")
}

func resolveImage(dir string, c components.ComponentConfig, ref string) (components.Image, error) {
	var img components.Image

	// A chart may already pin a digest; it is re-resolved from the tag and
	// compared below.
	name, chartDigest, _ := strings.Cut(ref, "@")
	slash := strings.LastIndex(name, "/")
	colon := strings.LastIndex(name, ":")
	if colon <= slash {
		return img, errors.New("the chart does not give this image a tag")
	}
	img.Repository, img.Tag = name[:colon], name[colon+1:]
	if img.Tag == "latest" {
		return img, errors.New("the chart uses the floating tag latest")
	}

	digest, err := output("crane", "digest", name)
	if err != nil {
		return img, err
	}
	if chartDigest != "" && chartDigest != digest {
		return img, fmt.Errorf("the chart pins %s but the tag resolves to %s", chartDigest, digest)
	}
	img.Digest = digest

	var signer *components.Signer
	for i, s := range c.Signers {
		if strings.HasPrefix(img.Repository, s.Images) {
			signer = &c.Signers[i]
			break
		}
	}
	if signer == nil {
		return img, errors.New("no signer rule in components.yaml matches this image")
	}
	v := signer.Verification
	v.Identity = strings.ReplaceAll(v.Identity, "{tag}", img.Tag)
	img.Verification = v

	return img, verify(dir, img)
}

// verify checks the image with cosign in the way its verification says.
func verify(dir string, img components.Image) error {
	v := img.Verification
	var args []string
	switch v.Method {
	case components.MethodNone:
		return nil
	case components.MethodKeyless:
		args = []string{"verify",
			"--certificate-identity", v.Identity,
			"--certificate-oidc-issuer", v.Issuer}
	case components.MethodKeylessProvenance:
		args = []string{"verify-attestation", "--type", "slsaprovenance",
			"--certificate-identity", v.Identity,
			"--certificate-oidc-issuer", v.Issuer,
			"--certificate-github-workflow-repository", v.SourceRepository}
	case components.MethodKey:
		// Checks the key file against its pinned hash before using it.
		if _, err := components.Key(v); err != nil {
			return err
		}
		args = []string{"verify",
			"--key", filepath.Join(dir, v.Key),
			"--signature-digest-algorithm", v.DigestAlgorithm,
			"--insecure-ignore-tlog=true"}
	default:
		return fmt.Errorf("unknown verification method %q", v.Method)
	}
	if _, err := output("cosign", append(args, img.Ref())...); err != nil {
		return fmt.Errorf("verification failed: %w", err)
	}
	return nil
}

// output runs a command and returns its trimmed standard output.
func output(name string, args ...string) (string, error) {
	cmd := exec.Command(name, args...)
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	if err := cmd.Run(); err != nil {
		msg := strings.TrimSpace(stderr.String())
		if len(msg) > 400 {
			msg = msg[len(msg)-400:]
		}
		return "", fmt.Errorf("%s %s: %w: %s", name, args[0], err, msg)
	}
	return strings.TrimSpace(stdout.String()), nil
}
